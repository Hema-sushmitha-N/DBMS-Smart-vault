-- SMARTVAULT | 01_schema.sql
-- Run once in a NEW, empty database named smartvault.
-- No DROP statements: existing objects are never silently removed.
BEGIN;
CREATE SCHEMA smartvault;
SET search_path TO smartvault, public;

CREATE TABLE app_users (
 user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(100) NOT NULL,
 email varchar(160) NOT NULL UNIQUE,
 role varchar(10) NOT NULL CHECK (role IN ('ADMIN','STAFF'))
);
-- Accounts are demonstration identities. Authentication is future application work.
CREATE TABLE categories (
 category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_name varchar(80) NOT NULL UNIQUE
);
CREATE TABLE suppliers (
 supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_name varchar(100) NOT NULL,
 email varchar(160) NOT NULL UNIQUE,
 phone varchar(20) NOT NULL
);
CREATE TABLE warehouses (
 warehouse_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 warehouse_name varchar(100) NOT NULL UNIQUE,
 city varchar(80) NOT NULL
);
CREATE TABLE products (
 product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku varchar(30) NOT NULL UNIQUE,
 product_name varchar(100) NOT NULL,
 category_id integer NOT NULL REFERENCES categories(category_id),
 preferred_supplier_id integer NOT NULL REFERENCES suppliers(supplier_id),
 unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE TABLE inventory (
 product_id integer NOT NULL REFERENCES products(product_id),
 warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
 quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
 reorder_level integer NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
 PRIMARY KEY (product_id, warehouse_id)
);
CREATE TABLE purchase_orders (
 order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_id integer NOT NULL REFERENCES suppliers(supplier_id),
 warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
 created_by integer NOT NULL REFERENCES app_users(user_id),
 order_date date NOT NULL,
 status varchar(12) NOT NULL CHECK (status IN ('DRAFT','PLACED','RECEIVED','CANCELLED'))
);
CREATE TABLE purchase_order_items (
 order_id integer NOT NULL REFERENCES purchase_orders(order_id),
 product_id integer NOT NULL REFERENCES products(product_id),
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_cost numeric(12,2) NOT NULL CHECK (unit_cost >= 0),
 PRIMARY KEY (order_id, product_id)
);
CREATE TABLE stock_movements (
 movement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id integer NOT NULL REFERENCES products(product_id),
 source_warehouse_id integer REFERENCES warehouses(warehouse_id),
 destination_warehouse_id integer REFERENCES warehouses(warehouse_id),
 movement_type varchar(10) NOT NULL CHECK (movement_type IN ('RECEIPT','ISSUE','TRANSFER')),
 quantity integer NOT NULL CHECK (quantity > 0),
 performed_by integer NOT NULL REFERENCES app_users(user_id),
 occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 note varchar(200),
 CHECK (
  (movement_type='RECEIPT' AND source_warehouse_id IS NULL AND destination_warehouse_id IS NOT NULL)
  OR (movement_type='ISSUE' AND source_warehouse_id IS NOT NULL AND destination_warehouse_id IS NULL)
  OR (movement_type='TRANSFER' AND source_warehouse_id IS NOT NULL
      AND destination_warehouse_id IS NOT NULL AND source_warehouse_id <> destination_warehouse_id)
 )
);
CREATE TABLE low_stock_alerts (
 alert_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id integer NOT NULL,
 warehouse_id integer NOT NULL,
 observed_quantity integer NOT NULL CHECK (observed_quantity >= 0),
 threshold integer NOT NULL CHECK (threshold >= 0),
 status varchar(8) NOT NULL CHECK (status IN ('OPEN','RESOLVED')),
 raised_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at timestamptz,
 UNIQUE (product_id, warehouse_id),
 FOREIGN KEY (product_id, warehouse_id) REFERENCES inventory(product_id, warehouse_id),
 CHECK ((status='OPEN' AND resolved_at IS NULL) OR (status='RESOLVED' AND resolved_at IS NOT NULL))
);
CREATE TABLE anomaly_logs (
 anomaly_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 movement_id integer NOT NULL UNIQUE REFERENCES stock_movements(movement_id),
 rule_name varchar(60) NOT NULL,
 reason varchar(200) NOT NULL,
 detected_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_products_supplier ON products(preferred_supplier_id);
CREATE INDEX idx_inventory_warehouse ON inventory(warehouse_id);
CREATE INDEX idx_orders_supplier_date ON purchase_orders(supplier_id, order_date);
CREATE INDEX idx_order_items_product ON purchase_order_items(product_id);
CREATE INDEX idx_movements_product_time ON stock_movements(product_id, occurred_at);
CREATE INDEX idx_movements_source_time ON stock_movements(source_warehouse_id, occurred_at);
CREATE INDEX idx_movements_destination_time ON stock_movements(destination_warehouse_id, occurred_at);

-- One alert state per product/warehouse; this is not an alert-event history.
CREATE FUNCTION sync_low_stock_alert() RETURNS trigger
LANGUAGE plpgsql SET search_path = smartvault, pg_temp AS $$
BEGIN
 IF NEW.quantity < NEW.reorder_level THEN
  INSERT INTO low_stock_alerts(product_id, warehouse_id, observed_quantity, threshold, status)
  VALUES (NEW.product_id, NEW.warehouse_id, NEW.quantity, NEW.reorder_level, 'OPEN')
  ON CONFLICT (product_id, warehouse_id) DO UPDATE SET
   observed_quantity=EXCLUDED.observed_quantity, threshold=EXCLUDED.threshold,
   raised_at=CASE WHEN low_stock_alerts.status='RESOLVED' THEN CURRENT_TIMESTAMP ELSE low_stock_alerts.raised_at END,
   status='OPEN', resolved_at=NULL;
 ELSE
  UPDATE low_stock_alerts SET observed_quantity=NEW.quantity,
   threshold=NEW.reorder_level, status='RESOLVED', resolved_at=CURRENT_TIMESTAMP
  WHERE product_id=NEW.product_id AND warehouse_id=NEW.warehouse_id;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER inventory_low_stock
AFTER INSERT OR UPDATE OF quantity, reorder_level ON inventory
FOR EACH ROW EXECUTE FUNCTION sync_low_stock_alert();

-- Inventory rows must exist before a movement. Lock both warehouses in a
-- consistent order. A failed destination update also rolls back the deduction.
CREATE FUNCTION apply_stock_movement() RETURNS trigger
LANGUAGE plpgsql SET search_path = smartvault, pg_temp AS $$
BEGIN
 PERFORM 1 FROM inventory
 WHERE product_id=NEW.product_id
 AND warehouse_id IN (NEW.source_warehouse_id, NEW.destination_warehouse_id)
 ORDER BY warehouse_id FOR UPDATE;
 IF NEW.source_warehouse_id IS NOT NULL THEN
  UPDATE inventory SET quantity=quantity-NEW.quantity
  WHERE product_id=NEW.product_id AND warehouse_id=NEW.source_warehouse_id
    AND quantity >= NEW.quantity;
  IF NOT FOUND THEN
   RAISE EXCEPTION 'Source inventory missing or insufficient stock';
  END IF;
 END IF;
 IF NEW.destination_warehouse_id IS NOT NULL THEN
  UPDATE inventory SET quantity=quantity+NEW.quantity
  WHERE product_id=NEW.product_id AND warehouse_id=NEW.destination_warehouse_id;
  IF NOT FOUND THEN
   RAISE EXCEPTION 'Destination inventory row does not exist';
  END IF;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER movement_applies_stock
BEFORE INSERT ON stock_movements
FOR EACH ROW EXECUTE FUNCTION apply_stock_movement();

CREATE FUNCTION detect_large_issue() RETURNS trigger
LANGUAGE plpgsql SET search_path = smartvault, pg_temp AS $$
BEGIN
 IF NEW.movement_type='ISSUE' AND NEW.quantity >= 50 THEN
  INSERT INTO anomaly_logs(movement_id, rule_name, reason, detected_at)
  VALUES (NEW.movement_id, 'LARGE_ISSUE',
   'Single issue of at least 50 units; review required, not proof of fraud.',
   NEW.occurred_at);
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER movement_detects_anomaly AFTER INSERT ON stock_movements
FOR EACH ROW EXECUTE FUNCTION detect_large_issue();

-- Posted movements are append-only. Correct them using compensating movements.
CREATE FUNCTION reject_movement_edit() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Posted stock movements cannot be updated or deleted';
END;
$$;
CREATE TRIGGER movement_immutable BEFORE UPDATE OR DELETE ON stock_movements
FOR EACH ROW EXECUTE FUNCTION reject_movement_edit();

CREATE FUNCTION transfer_stock(p_product integer, p_source integer,
 p_destination integer, p_quantity integer, p_user integer)
RETURNS integer LANGUAGE plpgsql SET search_path = smartvault, pg_temp AS $$
DECLARE result_id integer;
BEGIN
 INSERT INTO stock_movements(product_id, source_warehouse_id,
  destination_warehouse_id, movement_type, quantity, performed_by, note)
 VALUES (p_product,p_source,p_destination,'TRANSFER',p_quantity,p_user,'Warehouse transfer')
 RETURNING movement_id INTO result_id;
 RETURN result_id;
END;
$$;

CREATE VIEW v_inventory_report AS
SELECT p.product_id,p.sku,p.product_name,c.category_name,
 w.warehouse_id,w.warehouse_name,w.city,i.quantity,i.reorder_level,
 p.unit_price,i.quantity*p.unit_price AS stock_value,
 CASE WHEN i.quantity=0 THEN 'OUT OF STOCK'
      WHEN i.quantity<i.reorder_level THEN 'LOW STOCK' ELSE 'AVAILABLE' END AS availability
FROM inventory i JOIN products p USING(product_id)
JOIN categories c USING(category_id) JOIN warehouses w USING(warehouse_id);

CREATE VIEW v_purchase_order_totals AS
SELECT po.order_id,s.supplier_name,w.warehouse_name,po.order_date,po.status,
 COALESCE(SUM(poi.quantity*poi.unit_cost),0) AS order_total
FROM purchase_orders po JOIN suppliers s USING(supplier_id)
JOIN warehouses w USING(warehouse_id)
LEFT JOIN purchase_order_items poi USING(order_id)
GROUP BY po.order_id,s.supplier_name,w.warehouse_name,po.order_date,po.status;
COMMIT;
